window.CICM_LANG = (function () {
  var q = new URLSearchParams(location.search).get("lang");
  var saved = null;
  try { saved = localStorage.getItem("cicm-lang"); } catch (e) {}
  var l = q || saved || "en";
  return l === "th" ? "th" : "en";
})();

/* t(key, english) returns Thai when Thai is on and a translation exists */
window.t = function (key, en) {
  if (window.CICM_LANG === "th" && window.I18N.th[key]) return window.I18N.th[key];
  return en;
};
/* pick({en, th}) for content objects */
window.pick = function (o) {
  if (o == null) return "";
  if (typeof o === "string") return o;
  return (window.CICM_LANG === "th" && o.th) ? o.th : (o.en || "");
};
